/** Any play key advances the passage; the actual input never changes the story. */
export class StoryStream {
  private characters: string[];
  private index = 0;

  constructor(customText = '') {
    this.characters = Array.from(
      (customText.trim() || STORIES.join('\n\n')).replace(/\r\n?/g, '\n') +
        '\n\n',
    );
  }

  next(): { character: string; word: string } {
    const character = this.characters[this.index];
    const atWordStart =
      this.index === 0 || /\s/.test(this.characters[this.index - 1]);
    let word = '';
    if (atWordStart && !/\s/.test(character)) {
      for (
        let i = this.index;
        i < this.characters.length && !/\s/.test(this.characters[i]);
        i++
      )
        word += this.characters[i];
    }
    this.index = (this.index + 1) % this.characters.length;
    return { character, word };
  }

  reset(): void {
    this.index = 0;
  }
}
